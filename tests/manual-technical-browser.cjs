const assert = require('node:assert/strict')
const path = require('node:path')

module.exports = async function runTechnicalBrowserTests({page, admin, reviewer, pool, dev, origin, directory, preview}) {
  const workspace = (manual='proprietario', params='item=approved%3A%3Aunidade') => origin+'/empreendimentos/'+dev+'?modulo=elaboracao&aba=textos&manual='+manual+'&'+params
  const catalog = () => page.getByRole('navigation',{name:'Catálogo de textos técnicos'})
  const selectSystem = title => catalog().getByRole('button',{name:new RegExp('^4\\.\\d+ '+title+'$')})
  async function open(manual, params) {
    await page.goto(workspace(manual, params))
    await page.getByRole('heading',{name:'Textos técnicos',exact:true}).waitFor()
    await catalog().waitFor()
  }
  async function technical(manual='proprietario') {
    const result=await admin.get('/api/manuals/technical?developmentId='+dev+'&manualType='+manual)
    assert.equal(result.status(),200,await result.text())
    return result.json()
  }
  async function review(key,section) {
    const system=(await technical()).systems.find(system=>system.key===key)
    const result=await reviewer.post('/api/manuals/technical',{data:{developmentId:dev,manualType:'proprietario',contextKey:key,section,action:'approve',expectedFingerprint:section==='sistemas'?system.descriptionFingerprint:system.maintenanceFingerprint}})
    assert.equal(result.status(),200,await result.text())
  }
  await open('proprietario')
  await page.getByRole('heading',{name:'4.1 Estrutura',exact:true}).waitFor()
  assert.equal(await page.getByRole('button',{name:'Sistemas construtivos',exact:true}).count(),0)
  assert.equal(await page.getByRole('button',{name:'Textos técnicos',exact:true}).count(),1)
  assert.equal(await page.getByRole('tab',{name:'Descrição técnica',exact:true}).getAttribute('aria-selected'),'true')
  await page.locator('.tiptap[contenteditable="true"]').fill('DESCRICAO_TECNICA_EDITADA')
  await selectSystem('Pintura').click()
  await page.getByRole('heading',{name:'4.2 Pintura',exact:true}).waitFor()
  await selectSystem('Estrutura').click()
  assert.equal(await page.locator('.tiptap').innerText(),'DESCRICAO_TECNICA_EDITADA')
  await page.getByRole('tab',{name:'Manutenção',exact:true}).click()
  await page.getByRole('button',{name:'Adicionar atividade',exact:true}).click()
  await page.getByLabel('Atividade da linha 2', {exact:true}).fill('ATIVIDADE_PRESERVADA')
  await page.getByLabel('Periodicidade da linha 2', {exact:true}).fill('Mensal')
  await page.getByLabel('Responsável da linha 2', {exact:true}).selectOption('Proprietário')
  await page.getByLabel('Tipo de manual dos textos').selectOption('sindico')
  await selectSystem('Instalações hidráulicas').click()
  await page.getByRole('tab',{name:'Descrição técnica',exact:true}).click()
  assert.ok((await page.locator('.tiptap').innerText()).includes('COMUM_HIDRAULICA'))
  assert.equal(await selectSystem('Estrutura').count(),0)
  await page.getByLabel('Tipo de manual dos textos').selectOption('proprietario')
  await selectSystem('Estrutura').click()
  await page.getByRole('tab',{name:'Manutenção',exact:true}).click()
  await page.getByLabel('Atividade da linha 2', {exact:true}).waitFor()
  assert.equal(await page.getByLabel('Atividade da linha 2', {exact:true}).inputValue(),'ATIVIDADE_PRESERVADA')
  await page.getByRole('button',{name:'Remover atividade da linha 2',exact:true}).click()
  await page.getByLabel('Atividade da linha 1',{exact:true}).fill('MANUTENCAO_TECNICA_EDITADA')
  await page.getByLabel('Periodicidade da linha 1',{exact:true}).fill('Semestral')
  await page.getByRole('button',{name:'Salvar manutenção',exact:true}).click()
  await page.getByRole('status').filter({hasText:'Manutenção salva.'}).waitFor()
  const maintenanceSaved=(await technical()).systems.find(system=>system.key==='approved::unidade')
  assert.equal(maintenanceSaved.maintenanceStatus,'rascunho')
  assert.equal(maintenanceSaved.descriptionStatus,'aprovado')
  assert.ok(maintenanceSaved.html.includes('PRIVATIVO_approved'))
  assert.equal(maintenanceSaved.maintenance.length,1)
  assert.equal(maintenanceSaved.maintenance[0].frequency,'Semestral')
  await page.getByRole('tab',{name:'Descrição técnica',exact:true}).click()
  assert.equal(await page.locator('.tiptap').innerText(),'DESCRICAO_TECNICA_EDITADA')
  await page.getByRole('button',{name:'Salvar descrição',exact:true}).click()
  await page.getByRole('status').filter({hasText:'Descrição salva.'}).waitFor()
  assert.equal(await page.locator('.tiptap').innerText(),'DESCRICAO_TECNICA_EDITADA')
  await page.getByRole('button',{name:'Enviar para validação',exact:true}).click()
  await page.getByRole('status').filter({hasText:'Conteúdo enviado para validação.'}).waitFor()
  await page.getByRole('link',{name:'Visualizar no manual',exact:true}).click()
  await page.getByRole('navigation',{name:'Sumário do manual'}).waitFor()
  await page.waitForFunction(()=>[...document.querySelectorAll('[data-manual-page] svg text')].some(node=>node.textContent==='DESCRICAO_TECNICA_EDITADA'&&node.getAttribute('fill')==='#B77900'))
  await page.getByRole('button',{name:'Modo edição',exact:true}).click()
  await page.getByRole('link',{name:'Editar na Elaboração: DESCRICAO_TECNICA_EDITADA',exact:true}).click()
  await page.getByRole('heading',{name:'Textos técnicos',exact:true}).waitFor()
  assert.equal(new URL(page.url()).searchParams.get('aba'),'textos')
  assert.equal(new URL(page.url()).searchParams.get('item'),'approved::unidade')
  assert.equal(await page.getByRole('tab',{name:'Descrição técnica',exact:true}).getAttribute('aria-selected'),'true')
  await review('approved::unidade','sistemas')
  await open('proprietario','item=approved%3A%3Aunidade&conteudo=manutencao')
  await page.getByLabel('Atividade da linha 1',{exact:true}).waitFor()
  assert.equal(await page.getByLabel('Atividade da linha 1',{exact:true}).inputValue(),'MANUTENCAO_TECNICA_EDITADA')
  await page.getByRole('button',{name:'Enviar para validação',exact:true}).click()
  await page.getByRole('status').filter({hasText:'Conteúdo enviado para validação.'}).waitFor()
  await page.screenshot({path:path.join(directory,'textos-tecnicos-manutencao.png')})
  await page.getByRole('link',{name:'Visualizar no manual',exact:true}).click()
  await page.getByRole('navigation',{name:'Sumário do manual'}).waitFor()
  await page.waitForFunction(()=>[...document.querySelectorAll('[data-manual-page] svg text')].some(node=>node.textContent==='MANUTENCAO_TECNICA_EDITADA'&&node.getAttribute('fill')==='#B77900'))
  await page.getByRole('button',{name:'Modo edição',exact:true}).click()
  await page.getByRole('link',{name:'Editar na Elaboração: MANUTENCAO_TECNICA_EDITADA',exact:true}).first().click()
  await page.getByRole('heading',{name:'Textos técnicos',exact:true}).waitFor()
  assert.equal(new URL(page.url()).searchParams.get('conteudo'),'manutencao')
  assert.equal(await page.getByRole('tab',{name:'Manutenção',exact:true}).getAttribute('aria-selected'),'true')
  await review('approved::unidade','manutencao')
  await page.goto(workspace().replace('aba=textos','aba=sistemas')+'&conteudo=manutencao')
  await page.getByLabel('Atividade da linha 1',{exact:true}).waitFor()
  await page.waitForURL(url=>url.searchParams.get('aba')==='textos')
  assert.equal(await page.getByRole('tab',{name:'Manutenção',exact:true}).getAttribute('aria-selected'),'true')
  await page.getByLabel('Buscar textos técnicos').fill('nbr 5674')
  assert.equal(await selectSystem('Estrutura').count(),1)
  assert.equal(await catalog().getByRole('button',{name:/Finalidade do Manual/}).count(),0)
  await page.getByLabel('Buscar textos técnicos').fill('')
  assert.equal(await page.getByLabel('Tipo de texto').count(),0)
  assert.equal(await page.getByLabel('Estado do texto').count(),0)
  assert.equal(await page.getByLabel('Categoria do sistema').count(),0)
  assert.equal(await page.getByRole('button',{name:'Atualizar',exact:true}).count(),0)
  assert.equal(await page.getByText('Inserir variável',{exact:true}).count(),0)
  assert.equal(await selectSystem('Estrutura').count(),1)
  await page.getByRole('tab',{name:'Descrição técnica',exact:true}).click()
  await page.locator('.tiptap').filter({hasText:'DESCRICAO_TECNICA_EDITADA'}).waitFor()
  await page.screenshot({path:path.join(directory,'textos-tecnicos-descricao.png')})
  await open('sindico','item=approved%3A%3Aunidade')
  await page.getByRole('alert').filter({hasText:'pertence a outro manual'}).waitFor()
  assert.equal(await page.locator('.tiptap').count(),0)
  async function checklistChange(status) {
    await page.goto(origin+'/empreendimentos/'+dev+'?modulo=elaboracao&aba=checklist')
    await page.getByRole('button',{name:/^Sistemas .*itens$/}).click()
    const row=page.getByRole('row').filter({has:page.getByText('Estrutura',{exact:true})})
    await row.locator('select').selectOption(status)
    for(let attempt=0;attempt<50;attempt++) {
      const data=(await pool.query('SELECT data FROM development WHERE id=$1',[dev])).rows[0].data
      if(data.checklist.find(item=>item.id==='approved').status===status) return
      await page.waitForTimeout(100)
    }
    assert.fail('Checklist change was not persisted')
  }
  await checklistChange('nao_aplicado')
  const removed=await technical()
  assert.ok(!removed.systems.some(system=>system.key==='approved::unidade'))
  assert.ok(!JSON.stringify((await preview('proprietario')).document).includes('DESCRICAO_TECNICA_EDITADA'))
  await open('proprietario')
  await page.getByRole('alert').filter({hasText:/disponível|selecionado|checklist/}).waitFor()
  assert.equal(await page.locator('.tiptap').count(),0)
  await checklistChange('possui')
  await open('proprietario')
  await page.locator('.tiptap').filter({hasText:'DESCRICAO_TECNICA_EDITADA'}).waitFor()
  const restored=(await technical()).systems.find(system=>system.key==='approved::unidade')
  assert.equal(restored.descriptionStatus,'aprovado')
  assert.equal(restored.maintenanceStatus,'aprovado')
  assert.equal(restored.maintenance[0].task,'MANUTENCAO_TECNICA_EDITADA')
  // Adding a new checklist scope composes its structure without copying source
  // text or approval from the original manual.
  await page.goto(origin+'/empreendimentos/'+dev+'?modulo=elaboracao&aba=checklist')
  await page.getByRole('button',{name:/^Sistemas .*itens$/}).click()
  const structureRow=page.getByRole('row').filter({has:page.getByText('Estrutura',{exact:true})})
  await structureRow.getByRole('button',{name:'Áreas comuns',exact:true}).click()
  await page.getByRole('button',{name:'Textos técnicos',exact:true}).click()
  await open('sindico','item=approved%3A%3Acomum')
  await page.locator('.tiptap[contenteditable="true"]').waitFor()
  assert.equal((await page.locator('.tiptap').innerText()).trim(),'')
  const newScope=(await technical('sindico')).systems.find(system=>system.key==='approved::comum')
  assert.equal(newScope.html,'')
  assert.deepEqual(newScope.maintenance,[])
  assert.equal(newScope.descriptionStatus,'rascunho')
  assert.equal(newScope.maintenanceStatus,'rascunho')
  assert.ok(JSON.stringify((await preview('sindico')).document).includes('sistema-approved'))
  assert.equal((await technical()).systems.find(system=>system.key==='approved::unidade').html,restored.html)
  await open('proprietario','item=shared%3A%3Aunidade')
  // The shared system uses distinct sources, including after all owner-side edits.
  await page.locator('.tiptap').filter({hasText:'PRIVATIVO_shared'}).waitFor()
  assert.ok((await page.locator('.tiptap').innerText()).includes('PRIVATIVO_shared'))
  await page.getByLabel('Tipo de manual dos textos').selectOption('sindico')
  await selectSystem('Instalações hidráulicas').click()
  assert.ok((await page.locator('.tiptap').innerText()).includes('COMUM_HIDRAULICA'))
  await page.screenshot({path:path.join(directory,'textos-tecnicos-sindico.png')})
  await page.setViewportSize({width:390,height:844})
  await page.waitForFunction(()=>{
    const menu=document.querySelector('[aria-label="Fechar menu"]')?.closest('aside')
    return menu && menu.getBoundingClientRect().right<=0
  })
  await page.getByRole('heading',{name:'Textos técnicos',exact:true}).waitFor()
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),true,'Technical workspace should fit a narrow viewport')
  await page.getByRole('heading',{name:/4\.\d+ Instalações hidráulicas/,exact:true}).scrollIntoViewIfNeeded()
  await page.getByRole('tab',{name:'Manutenção',exact:true}).click()
  await page.getByText('Nenhuma atividade de manutenção cadastrada.',{exact:true}).waitFor()
  await page.screenshot({path:path.join(directory,'textos-tecnicos-mobile.png')})
  await page.setViewportSize({width:1600,height:1100})
  console.log('TECHNICAL_BROWSER_PASS: unified catalog/filter/legacy links, description+maintenance saved/reviewed independently, draft retention, source clicks, new/manual scopes, checklist removal/restoration and narrow viewport')
}
