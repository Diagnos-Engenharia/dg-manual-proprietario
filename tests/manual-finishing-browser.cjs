const assert = require('node:assert/strict')
const path = require('node:path')

module.exports = async function runFinishingBrowserTests({ page, admin, reviewer, dev, origin, directory, units }) {
  const sourceHref = id => origin + '/empreendimentos/' + dev + '?' + new URLSearchParams({ modulo: 'elaboracao', aba: 'acabamentos', unidade: id })
  const nativeDialogs = []
  const listener = dialog => { nativeDialogs.push(dialog.type()); void dialog.dismiss() }
  page.on('dialog', listener)
  try {
    await page.goto(sourceHref(units.second.id))
    await page.getByRole('heading', { name: 'Tabela de Acabamentos', exact: true }).waitFor()
    await page.getByLabel('Teto da linha 1', { exact: true }).waitFor()
    await page.getByRole('button', { name: 'Cadastrar unidade', exact: true }).click()
    const dialog = page.getByRole('dialog')
    assert.equal(await dialog.getByRole('textbox').count(), 2, 'Unit registration only asks for number and tower')
    for (const removed of [/^Tipologia/, /^Pavimento/, /^Área da unidade/]) assert.equal(await dialog.getByLabel(removed).count(), 0)
    assert.ok(await dialog.getByRole('button', { name: 'Cadastrar unidade', exact: true }).isDisabled(), 'Number is required')
    await dialog.getByLabel('Número da unidade *', { exact: true }).fill('201')
    assert.ok(await dialog.getByRole('button', { name: 'Cadastrar unidade', exact: true }).isEnabled(), 'Tower is optional')
    await dialog.getByLabel('Torre ou bloco', { exact: true }).fill('Torre A')
    await page.screenshot({ path: path.join(directory, 'acabamentos-cadastro-simplificado.png') })
    const createdResponse = page.waitForResponse(response => response.url().endsWith('/api/finishing/units') && response.request().method() === 'POST' && response.ok())
    await dialog.getByRole('button', { name: 'Cadastrar unidade', exact: true }).click()
    const createdHttp = await createdResponse
    const submittedUnit = createdHttp.request().postDataJSON()
    assert.deepEqual(Object.keys(submittedUnit).sort(), ['developmentId', 'number', 'tower'])
    for (const removed of ['floor', 'typology', 'area']) assert.equal(Object.hasOwn(submittedUnit, removed), false, 'Registration omits legacy field ' + removed)
    const created = (await createdHttp.json()).unit
    await dialog.waitFor({ state: 'hidden' })
    await page.getByRole('heading', { name: 'Torre A · Unidade 201', exact: true }).waitFor()
    await page.waitForURL(url => url.searchParams.get('unidade') === created.id)
    assert.equal(new URL(page.url()).searchParams.get('unidade'), created.id)
    await page.getByRole('button', { name: 'Copiar base existente', exact: true }).click()
    await dialog.getByLabel('Base de acabamentos').selectOption({ index: 1 })
    assert.equal(await dialog.getByLabel('Unidade de destino da cópia').inputValue(), created.id)
    await dialog.getByRole('button', { name: 'Copiar para o rascunho', exact: true }).click()
    await dialog.waitFor({ state: 'hidden' })
    await page.getByLabel('Teto da linha 1', { exact: true }).fill('ACABAMENTO_UI_UNIDADE_201_ÁRVORE')
    await page.reload()
    await page.getByLabel('Teto da linha 1', { exact: true }).waitFor()
    assert.equal(await page.getByLabel('Teto da linha 1', { exact: true }).inputValue(), 'ACABAMENTO_UI_UNIDADE_201_ÁRVORE', 'Reload preserves the copied draft')
    await page.goto(origin + '/empreendimentos/' + dev + '?modulo=informacoes')
    await page.goBack()
    await page.getByLabel('Teto da linha 1', { exact: true }).waitFor()
    assert.equal(await page.getByLabel('Teto da linha 1', { exact: true }).inputValue(), 'ACABAMENTO_UI_UNIDADE_201_ÁRVORE', 'Browser Back preserves the draft')
    await page.getByRole('button', { name: 'Adicionar ambiente', exact: true }).click()
    await page.getByLabel('Ambiente da linha 2', { exact: true }).fill('Banheiro')
    await page.getByRole('button', { name: 'Excluir ambiente Banheiro', exact: true }).click()
    await dialog.getByRole('heading', { name: 'Excluir ambiente e seus itens?', exact: true }).waitFor()
    await dialog.getByRole('button', { name: 'Cancelar', exact: true }).click()
    assert.equal(await page.getByLabel('Ambiente da linha 2', { exact: true }).inputValue(), 'Banheiro')
    await page.getByRole('button', { name: 'Excluir ambiente Banheiro', exact: true }).click()
    await dialog.getByRole('button', { name: 'Excluir ambiente e itens', exact: true }).click()
    assert.equal(await page.getByLabel('Ambiente da linha 2', { exact: true }).count(), 0)
    await page.getByRole('navigation', { name: 'Unidades cadastradas', exact: true }).getByRole('button', { name: /^Torre A · Unidade 102/ }).click()
    await page.getByRole('heading', { name: 'Torre A · Unidade 102', exact: true }).waitFor()
    assert.equal(await page.getByLabel('Teto da linha 1', { exact: true }).inputValue(), 'ACABAMENTO_UNIDADE_102_SÃO_JOÃO')
    await page.getByRole('navigation', { name: 'Unidades cadastradas', exact: true }).getByRole('button', { name: /^Torre A · Unidade 201/ }).click()
    await page.getByRole('heading', { name: 'Torre A · Unidade 201', exact: true }).waitFor()
    assert.equal(await page.getByLabel('Teto da linha 1', { exact: true }).inputValue(), 'ACABAMENTO_UI_UNIDADE_201_ÁRVORE')
    await page.getByRole('button', { name: 'DATABOOK', exact: true }).click()
    await dialog.getByRole('heading', { name: 'Descartar alterações?', exact: true }).waitFor()
    await dialog.getByRole('button', { name: 'Continuar editando', exact: true }).click()
    assert.equal(await page.getByLabel('Teto da linha 1', { exact: true }).inputValue(), 'ACABAMENTO_UI_UNIDADE_201_ÁRVORE')
    await page.getByRole('button', { name: 'Salvar tabela', exact: true }).click()
    await page.getByRole('status').filter({ hasText: 'Tabela salva como rascunho' }).waitFor()
    const draftPreviewResponse = await admin.post('/api/manuals/preview', { data: { developmentId: dev, manualType: 'acabamentos', unitId: created.id } })
    assert.equal(draftPreviewResponse.status(), 200)
    const draftPreview = await draftPreviewResponse.json()
    assert.ok(JSON.stringify(draftPreview.document).includes('ACABAMENTO_UI_UNIDADE_201'), 'Saved draft items must be visible in Preview before validation')
    await page.getByRole('button', { name: 'Enviar para validação', exact: true }).click()
    await page.getByRole('status').filter({ hasText: 'Tabela enviada para validação' }).waitFor()
    assert.ok(await page.getByLabel('Teto da linha 1', { exact: true }).isDisabled())
    const currentResponse = await admin.get('/api/finishing/tables?' + new URLSearchParams({ developmentId: dev, unitId: created.id }))
    const current = (await currentResponse.json()).unit
    const approve = await reviewer.post('/api/finishing/tables', { data: { developmentId: dev, unitId: created.id, action: 'approve', expectedFingerprint: current.fingerprint } })
    assert.equal(approve.status(), 200, await approve.text())
    await page.reload()
    await page.getByRole('link', { name: 'Visualizar PDF', exact: true }).waitFor()
    await page.screenshot({ path: path.join(directory, 'acabamentos-elaboracao-unidade.png') })
    const previewResponse = page.waitForResponse(response => response.url().endsWith('/api/manuals/preview') && response.request().method() === 'POST' && response.request().postDataJSON()?.unitId === created.id && response.ok())
    await page.getByRole('link', { name: 'Visualizar PDF', exact: true }).click()
    await page.getByRole('navigation', { name: 'Sumário do manual', exact: true }).waitFor()
    assert.equal(await page.getByLabel('Tipo de manual').inputValue(), 'acabamentos')
    assert.equal(await page.getByLabel('Unidade da tabela').inputValue(), created.id)
    assert.equal(await page.getByRole('button', { name: 'Módulos', exact: true }).count(), 0)
    const preview = await (await previewResponse).json()
    assert.deepEqual(preview.document.sections.map(section => section.id), ['acabamentos'], 'The unit table has one outline section')
    assert.equal(preview.layout.pages[0].number, 1)
    assert.ok(preview.layout.pages[0].width > preview.layout.pages[0].height, 'The first page uses landscape A4')
    await page.waitForFunction(() => Array.from(document.querySelectorAll('[data-manual-page] svg')).some(svg => svg.textContent.includes('ACABAMENTO_UI_UNIDADE_201')))
    const outline = page.getByRole('navigation', { name: 'Sumário do manual', exact: true })
    assert.equal(await outline.getByRole('button').count(), 1, 'The outline contains only the finishing table')
    for (const removed of [/Capa/, /Sumário/, /Identificação da unidade/]) assert.equal(await outline.getByRole('button', { name: removed }).count(), 0)
    await page.getByLabel('Modo de visualização').selectOption('single')
    await outline.getByRole('button', { name: /Tabela de acabamentos/ }).click()
    assert.equal(await page.getByLabel('Ir para página').inputValue(), '1')
    const initialWidth = await page.locator('[data-manual-page]').first().evaluate(element => element.getBoundingClientRect().width)
    await page.getByRole('button', { name: 'Aumentar zoom', exact: true }).click()
    await page.waitForFunction(previousWidth => document.querySelector('[data-manual-page]')?.getBoundingClientRect().width > previousWidth, initialWidth)
    assert.equal(await page.getByLabel('Ir para página').inputValue(), '1', 'Zoom retains the current page')
    const firstSvg = await page.locator('[data-manual-page] svg').first().evaluate(svg => ({ width: svg.viewBox.baseVal.width, height: svg.viewBox.baseVal.height }))
    assert.ok(firstSvg.width > firstSvg.height, 'The displayed SVG uses the same landscape geometry')
    await page.screenshot({ path: path.join(directory, 'acabamentos-previa-unidade.png') })
    await page.getByRole('button', { name: 'Modo edição', exact: true }).click()
    await outline.getByRole('button', { name: /Tabela de acabamentos/ }).click()
    await page.getByLabel('Teto da linha 1', { exact: true }).waitFor()
    assert.equal(new URL(page.url()).searchParams.get('unidade'), created.id)
    assert.equal(new URL(page.url()).searchParams.get('grupo'), 'ambientes')
    assert.equal(new URL(page.url()).searchParams.get('ambiente'), null, 'The outline opens the whole table without an environment filter')
    assert.equal(await page.getByLabel('Buscar itens da tabela').inputValue(), '')
    await page.getByRole('link', { name: 'Visualizar PDF', exact: true }).click()
    await page.waitForFunction(() => Array.from(document.querySelectorAll('[data-manual-page] svg')).some(svg => svg.textContent.includes('ACABAMENTO_UI_UNIDADE_201')))
    await page.getByRole('button', { name: 'Modo edição', exact: true }).click()
    const bodyEdit = page.locator('[data-manual-page] svg a[role="link"]').filter({ hasText: 'ACABAMENTO_UI_UNIDADE_201' }).first()
    const bodyTarget = new URL(await bodyEdit.getAttribute('href'), origin)
    assert.equal(bodyTarget.searchParams.get('unidade'), created.id)
    assert.equal(bodyTarget.searchParams.get('grupo'), 'ambientes')
    assert.equal(bodyTarget.searchParams.get('ambiente'), 'Cozinha')
    await bodyEdit.click()
    await page.getByLabel('Teto da linha 1', { exact: true }).waitFor()
    assert.equal(new URL(page.url()).searchParams.get('unidade'), created.id)
    assert.equal(new URL(page.url()).searchParams.get('grupo'), 'ambientes')
    assert.equal(new URL(page.url()).searchParams.get('ambiente'), 'Cozinha')
    assert.equal(await page.getByLabel('Buscar itens da tabela').inputValue(), 'Cozinha')
    await page.getByRole('link', { name: 'Visualizar PDF', exact: true }).click()
    await page.getByRole('button', { name: 'Gerar PDF', exact: true }).waitFor()
    await page.getByRole('button', { name: 'Gerar PDF', exact: true }).click()
    const history = page.getByRole('dialog').locator('article').first()
    await history.getByText('Rev. 01', { exact: true }).waitFor()
    for (const action of ['Enviar para validação', 'Aprovar documento', 'Publicar']) await history.getByRole('button', { name: action, exact: true }).click()
    await history.getByText('Publicado', { exact: true }).waitFor()
    await page.keyboard.press('Escape')
    await page.getByRole('link', { name: 'Unidades em Manuais', exact: true }).click()
    await page.getByRole('heading', { name: 'Unidades cadastradas', exact: true }).waitFor()
    for (const record of [units.first, units.second, units.third, created]) await page.locator('article[data-unit-id="' + record.id + '"]').waitFor()
    assert.ok((await page.locator('article[data-unit-id="' + units.first.id + '"]').textContent()).includes('Atualização pendente'))
    assert.ok((await page.locator('article[data-unit-id="' + units.third.id + '"]').textContent()).includes('Pendente de emissão'))
    const published = page.locator('article[data-unit-id="' + created.id + '"]')
    assert.ok((await published.textContent()).includes('Emitida'))
    assert.ok(await published.getByRole('link', { name: 'Baixar PDF', exact: true }).getAttribute('href'))
    await page.getByRole('button', { name: /^Pendente de emissão/ }).click()
    assert.equal(await page.locator('article[data-unit-id="' + created.id + '"]').count(), 0)
    await page.locator('article[data-unit-id="' + units.third.id + '"]').waitFor()
    await page.getByRole('button', { name: /^Todas/ }).click()
    await page.getByLabel('Buscar manuais').fill('201')
    await published.waitFor()
    assert.equal(await page.locator('article[data-unit-id="' + units.second.id + '"]').count(), 0)
    await page.getByLabel('Buscar manuais').fill('')
    await page.screenshot({ path: path.join(directory, 'manuais-unidades.png') })
    await page.setViewportSize({ width: 390, height: 844 })
    await page.screenshot({ path: path.join(directory, 'manuais-unidades-mobile.png') })
    await page.setViewportSize({ width: 1600, height: 1100 })
    await page.goto(sourceHref(created.id))
    await page.getByLabel('Teto da linha 1', { exact: true }).fill('DESCARTAR_ESTA_ALTERACAO')
    await page.getByRole('button', { name: 'DATABOOK', exact: true }).click()
    await page.getByRole('dialog').getByRole('button', { name: 'Descartar e sair', exact: true }).click()
    await page.getByRole('heading', { name: 'DATABOOK', exact: true }).waitFor()
    await page.goto(sourceHref(created.id))
    await page.getByLabel('Teto da linha 1', { exact: true }).waitFor()
    assert.equal(await page.getByLabel('Teto da linha 1', { exact: true }).inputValue(), 'ACABAMENTO_UI_UNIDADE_201_ÁRVORE', 'Confirmed discard removes the session draft')
    assert.deepEqual(nativeDialogs, [])
  } finally { page.off('dialog', listener) }
}
