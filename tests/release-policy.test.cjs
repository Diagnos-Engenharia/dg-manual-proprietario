test('release evidence fails closed when stale, failed, incomplete or missing a responsive viewport', () => {
  assert.equal(validateAttestation(passed(), 'abc'), true)
  assert.throws(() => validateAttestation(passed(), 'different'), /stale/)
  const changed = passed(); changed.materialFiles = [{ path: 'scripts/migration-policy.d.mts', sha256: 'old' }]
  assert.throws(() => validateAttestation(changed, 'different', [{ path: 'scripts/migration-policy.d.mts', sha256: 'new' }]), /scripts\/migration-policy\.d\.mts/)
  const failed = passed(); failed.status = 'failed'; assert.throws(() => validateAttestation(failed, 'abc'))
  const incomplete = passed(); incomplete.stages = incomplete.stages.filter(stage => stage.name !== 'audit-runtime'); assert.throws(() => validateAttestation(incomplete, 'abc'), /audit-runtime/)
  const missing = passed(); missing.matrices[0].results.pop(); assert.throws(() => validateAttestation(missing, 'abc'), /desktop/)
})
test('material fingerprint covers new source/test/config files and excludes documentation/attestation churn', () => {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'dg-release-policy-'))
  try {
    fs.mkdirSync(path.join(root, 'app')); fs.mkdirSync(path.join(root, 'tests')); fs.mkdirSync(path.join(root, 'scripts')); fs.mkdirSync(path.join(root, 'hooks')); fs.mkdirSync(path.join(root, '.qa'))
    fs.writeFileSync(path.join(root, 'app', 'page.tsx'), 'source\r\nline\r\n'); fs.writeFileSync(path.join(root, 'scripts', 'migration-policy.d.mts'), 'declare const migration: string\r\n'); fs.writeFileSync(path.join(root, 'package.json'), '{}')
    const before = materialFingerprint(root), beforeManifest = materialManifest(root)
    assert.ok(beforeManifest.some(file => file.path === 'scripts/migration-policy.d.mts'))
    fs.writeFileSync(path.join(root, 'app', 'page.tsx'), 'source\nline\n'); assert.equal(materialFingerprint(root), before, 'Windows CRLF and Linux LF must attest the same material sources')
    fs.writeFileSync(path.join(root, 'scripts', 'migration-policy.d.mts'), 'declare const migration: string\n'); assert.equal(materialFingerprint(root), before, 'TypeScript .mts declaration files must normalize Windows CRLF and Linux LF')
    assert.deepEqual(materialManifest(root), beforeManifest, 'The diagnostic manifest must use the same normalized source bytes')
    fs.writeFileSync(path.join(root, 'README.md'), 'doc'); fs.writeFileSync(path.join(root, '.qa', 'release-attestation.json'), '{}')
    fs.writeFileSync(path.join(root, 'scripts', 'RELEASE.md'), 'operational documentation')
    assert.equal(materialFingerprint(root), before)
    assert.deepEqual(changedMaterialFiles(beforeManifest, materialManifest(root)), [])
    fs.writeFileSync(path.join(root, 'tests', 'future.test.ts'), 'new regression')
    assert.notEqual(materialFingerprint(root), before); assert.deepEqual(changedMaterialFiles(beforeManifest, materialManifest(root)), ['tests/future.test.ts'])
    const tests = materialFingerprint(root); fs.writeFileSync(path.join(root, 'package.json'), '{"changed":true}')
    assert.notEqual(materialFingerprint(root), tests); assert.deepEqual(changedMaterialFiles(beforeManifest, materialManifest(root)), ['package.json', 'tests/future.test.ts'])
    const config = materialFingerprint(root); fs.writeFileSync(path.join(root, 'hooks', 'use-review.ts'), 'export const useReview = () => true')
    assert.notEqual(materialFingerprint(root), config)
  } finally {
    const target = fs.realpathSync(root)
    assert.equal(path.dirname(target), fs.realpathSync(os.tmpdir()))
    assert.ok(path.basename(target).startsWith('dg-release-policy-'))
    fs.rmSync(target, { recursive: true, force: true })
  }
})

test('hosted verification ignores only Vercel config absent from the attested source tree', () => {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'dg-vercel-source-'))
  try {
    fs.mkdirSync(path.join(root, 'app'))
    fs.writeFileSync(path.join(root, 'app', 'page.tsx'), 'source\n')
    const sourceManifest = materialManifest(root)
    const sourceFingerprint = materialFingerprint(root)
    fs.writeFileSync(path.join(root, 'vercel.json'), '{"generated":true}\n')

    const generated = materialSnapshot(root, sourceManifest, { VERCEL: '1' })
    assert.equal(generated.fingerprint, sourceFingerprint)
    assert.deepEqual(generated.materialFiles, sourceManifest)
    const unexpectedLocalConfig = materialSnapshot(root, sourceManifest, {})
    assert.notEqual(unexpectedLocalConfig.fingerprint, sourceFingerprint)
    assert.deepEqual(changedMaterialFiles(sourceManifest, unexpectedLocalConfig.materialFiles), ['vercel.json'])

    const versionedManifest = materialManifest(root)
    const versionedFingerprint = materialFingerprint(root)
    fs.writeFileSync(path.join(root, 'vercel.json'), '{"generated":false}\n')
    const versioned = materialSnapshot(root, versionedManifest, { VERCEL: '1' })
    assert.notEqual(versioned.fingerprint, versionedFingerprint)
    assert.deepEqual(changedMaterialFiles(versionedManifest, versioned.materialFiles), ['vercel.json'])
  } finally {
    const target = fs.realpathSync(root)
    assert.equal(path.dirname(target), fs.realpathSync(os.tmpdir()))
    fs.rmSync(target, { recursive: true, force: true })
  }
})
