test('DEH report schema is parseable and requires the review and evidence contract', () => {
  const schemaPath = path.join(__dirname, '..', 'docs', 'engineering-harness', 'review-output.schema.json')
  const schema = JSON.parse(fs.readFileSync(schemaPath, 'utf8'))
  const required = ['snapshot', 'reviews', 'findings', 'checks', 'visual', 'preview', 'divergences', 'limitations', 'consolidatedBy', 'implementationOwner']
  assert.deepEqual(schema.required, required)
  assert.equal(schema.$defs.snapshot.required.includes('repo'), true)
  assert.equal(schema.$defs.snapshot.required.includes('pr'), true)
  assert.equal(schema.$defs.snapshot.required.includes('baseSha'), true)
  assert.equal(schema.$defs.snapshot.required.includes('headSha'), true)
  assert.deepEqual(schema.$defs.reviewRole.enum, ['DSI', 'Diagnos QA', 'DRAEL', 'LURIEL', 'Security', 'Code Review'])
  assert.deepEqual(schema.properties.reviews.allOf.map(rule => rule.contains.properties.role.const), ['DSI', 'Diagnos QA', 'DRAEL', 'LURIEL', 'Security', 'Code Review'])
  assert.ok(schema.$defs.review.required.includes('snapshotRef'))
  assert.equal(schema.$defs.review.properties.snapshotRef.const, '#/snapshot')
  assert.equal(Object.hasOwn(schema.$defs.review.properties, 'baseSha'), false)
  assert.equal(Object.hasOwn(schema.$defs.review.properties, 'headSha'), false)
  assert.equal(schema.properties.consolidatedBy.const, 'ASTRA')
  assert.equal(schema.properties.implementationOwner.const, 'LUNA')
  assert.ok(schema.$defs.finding.required.includes('evidence'))
  assert.ok(schema.$defs.finding.required.includes('disposition'))
  assert.ok(schema.$defs.evidence.properties.kind.enum.includes('self_attestation'))
  assert.ok(schema.$defs.evidence.properties.kind.enum.includes('static'))
  assert.ok(schema.$defs.check.properties.status.enum.includes('not_run'))
  assert.ok(schema.$defs.check.allOf.some(rule => rule.if.properties.status.const === 'passed' && rule.then.required.includes('evidence')))
  assert.deepEqual(schema.$defs.check.allOf.find(rule => rule.if.properties.status.const === 'passed').then.properties.evidence.properties.kind.enum, ['static', 'command', 'browser', 'preview', 'deployment'])
  assert.ok(schema.$defs.check.allOf.some(rule => rule.if.properties.evidence?.properties?.kind?.const === 'command' && rule.then.required.includes('command')))
  assert.ok(schema.$defs.visual.properties.scenarios.allOf.some(rule => rule.contains.properties.viewport.const === 'mobile'))
  assert.ok(schema.$defs.visual.properties.scenarios.allOf.some(rule => rule.contains.properties.viewport.const === 'tablet'))
  assert.ok(schema.$defs.visual.properties.scenarios.allOf.some(rule => rule.contains.properties.viewport.const === 'desktop'))
  assert.ok(schema.$defs.visualScenario.allOf.some(rule => rule.if.properties.status.const === 'passed' && rule.then.required.includes('evidence')))
  assert.equal(schema.$defs.visualScenario.allOf.find(rule => rule.if.properties.status.const === 'passed').then.properties.evidence.properties.kind.const, 'browser')
  assert.ok(schema.$defs.preview.properties.status.enum.includes('unavailable'))
  assert.ok(schema.$defs.preview.required.includes('deploymentState'))
  assert.ok(schema.$defs.preview.properties.deploymentState.enum.includes('not_applicable'))
  assert.ok(schema.$defs.preview.allOf.some(rule => rule.if.properties.status?.enum?.includes('available') && rule.then.required.includes('evidence') && rule.then.properties.evidence.properties.kind.enum.includes('deployment')))
  assert.ok(schema.$defs.preview.allOf.some(rule => rule.if.properties.deploymentState?.enum?.includes('ready') && rule.then.required.includes('evidence')))
  assert.ok(schema.$defs.preview.allOf.some(rule => rule.if.properties.functionalQa?.const === 'passed' && rule.then.required.includes('evidence')))
  assert.deepEqual(schema.$defs.preview.allOf.find(rule => rule.if.properties.functionalQa?.const === 'passed').then.properties.evidence.properties.kind.enum, ['browser', 'preview'])
})

